-- 建表脚本（PostgreSQL 16）：每个接线类一个独立 schema（`类名小写`），故 DDL 可以 drop + create 幂等。
-- 不写 COLLATE：夹具与查询参数全小写、无大小写非匹配断言。
-- 标识符全部裸小写（JDBC 后端渲染裸标识符）；`version`/`status` 在 PG 不是保留字。
drop table if exists asset;
drop table if exists owner;
drop table if exists item;
drop table if exists generated_item;
drop table if exists versioned_item;
drop table if exists ordinal_item;
drop table if exists managed_association;
drop table if exists "order";
create table item (id bigint primary key, name varchar(255), score int, score2 int, note varchar(255), status varchar(32));
create table owner (id bigint primary key, name varchar(255));
create table asset (id bigint primary key, name varchar(255), owner_id bigint, constraint fk_asset_owner foreign key (owner_id) references owner (id));
create table generated_item (id bigint generated by default as identity primary key, name varchar(255));
create table versioned_item (id bigint primary key, name varchar(255), version bigint not null default 0);
create table ordinal_item (id bigint primary key, status int);
create table managed_association (id bigint primary key, owner_id bigint);
create table "order" ("id" bigint primary key, "name" varchar(255), "desc" varchar(255), "key" int);

drop table if exists extended_item;
drop table if exists embedded_profile;
drop table if exists converted_item;
drop table if exists flag_column_item;
drop table if exists short_versioned_item;
drop table if exists short_generated_item;
create table extended_item (id bigint primary key, flag_col boolean, ratio_col double precision, weight_col real, count_col smallint, price_col numeric(18,2), serial_col bigint, birth_date date, created_at timestamp, wake_time time, synced_at timestamp, sql_date date, sql_time time, sql_timestamp timestamp);
create table embedded_profile (id bigint primary key, town varchar(64), address_street varchar(128), label varchar(64));
create table converted_item (id bigint primary key, status varchar(32), note varchar(64));
create table flag_column_item (id bigint primary key, name varchar(64), created_by varchar(64));
create table short_versioned_item (id bigint primary key, name varchar(255), version smallint not null default 0);
create table short_generated_item (id smallint generated by default as identity primary key, name varchar(255));

-- 3.1.0 golden schema：独立三表夹具（客户/订单/订单行）。
drop table if exists golden_order_line;
drop table if exists golden_order;
drop table if exists golden_customer;
create table golden_customer (id bigint primary key, display_name varchar(64), tier varchar(16), credit_limit numeric(12,2), active boolean, joined_at timestamp, addr_street varchar(64), addr_city varchar(32), addr_zip varchar(12), version bigint not null default 0);
create table golden_order (id bigint primary key, customer_id bigint, state varchar(16), total numeric(12,2), placed_at timestamp, note varchar(128), version bigint not null default 0, constraint fk_golden_order_customer foreign key (customer_id) references golden_customer (id));
create table golden_order_line (id bigint primary key, order_id bigint, line_no int, quantity int, unit_price numeric(12,2), shipped boolean, shipped_at timestamp, constraint fk_golden_line_order foreign key (order_id) references golden_order (id));

-- 3.1.0 legacy 形状：一个标量字段与一个只读关联映射同一列（`department_id`），外加可写反向对照关联。
drop table if exists dual_mapped_employee;
drop table if exists dual_mapped_department;
create table dual_mapped_department (id bigint primary key, name varchar(64));
create table dual_mapped_employee (id bigint primary key, name varchar(64), department_id bigint, manager_department_id bigint);
