/// 查询契约：用户写下的表达式（`Path` / `Predicate` / 聚合投影）与查询链的步骤接口。
///
/// 职责：承载「用户想查什么」，并让它在编译期类型安全——链上每一步只暴露下一步允许的算子。
///
/// 非目标（本包刻意不做的事）：
/// - 不求值、不拼 SQL/Criteria、不判断空集合这类语义；把表达式翻译成 `core.spec` 节点是后端的唯一职责，
///   因此语义只有一份，不会出现「api 一套、后端一套」的双份实现；
/// - 不出现任何三方类型：本包零三方依赖，锁模式、排序方向、运算种类都用本包自己的枚举表达，
///   后端负责把它们映射成自己的类型（JPA 侧把 {@link io.github.nextentity.api.LockMode} 映射成
///   `LockModeType`）；
/// - 不做「值对象兼作方法引用」的兼容捷径：`PathRef` 是用户写的方法引用（后端靠 `SerializedLambda`
///   解析属性名），`Path` 是纯值对象，两者刻意不互相继承。
///
/// 兼容性：本包是对外契约，删除或收窄签名属于破坏性变更，受 AGENTS「公开 API 是契约」的门禁约束。
