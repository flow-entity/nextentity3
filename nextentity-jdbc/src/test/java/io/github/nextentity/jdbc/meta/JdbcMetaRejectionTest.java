package io.github.nextentity.jdbc.meta;

import static org.assertj.core.api.Assertions.assertThatThrownBy;

import jakarta.persistence.AttributeConverter;
import jakarta.persistence.Column;
import jakarta.persistence.Convert;
import jakarta.persistence.Converter;
import jakarta.persistence.Embeddable;
import jakarta.persistence.Embedded;
import jakarta.persistence.EmbeddedId;
import jakarta.persistence.Entity;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.IdClass;
import jakarta.persistence.Inheritance;
import jakarta.persistence.InheritanceType;
import jakarta.persistence.Version;
import java.math.BigDecimal;
import java.sql.Timestamp;
import java.time.Instant;
import org.junit.jupiter.api.Test;

/// meta 期拒绝矩阵（§4.3 #1-#14）：非法映射在「用到该类型时」拒绝，消息是契约的一部分。
class JdbcMetaRejectionTest {

    private final JdbcMeta meta = new JdbcMeta();

    private void rejected(Class<?> type, String message) {
        assertThatThrownBy(() -> meta.entityType(type))
                .as("%s 应在 meta 期被拒绝", type.getSimpleName())
                .isInstanceOf(IllegalArgumentException.class)
                .hasMessage(message);
    }

    private void rejectedUnsupported(Class<?> type, String message) {
        assertThatThrownBy(() -> meta.entityType(type))
                .as("%s 应在 meta 期被拒绝", type.getSimpleName())
                .isInstanceOf(UnsupportedOperationException.class)
                .hasMessage(message);
    }

    @Test
    void entityWithoutAnnotationIsRejected() {
        rejected(NoEntityClass.class, "缺少 @Entity 注解: " + NoEntityClass.class.getName());
    }

    @Test
    void entityWithoutIdIsRejected() {
        rejected(NoIdEntity.class, "实体必须有且只有一个 @Id 字段: " + NoIdEntity.class.getName());
    }

    @Test
    void entityWithTwoIdsIsRejected() {
        rejected(TwoIdEntity.class, "实体必须有且只有一个 @Id 字段: " + TwoIdEntity.class.getName());
    }

    @Test
    void embeddedIdIsRejected() {
        rejectedUnsupported(EmbeddedIdEntity.class, "复合主键未支持: " + EmbeddedIdEntity.class.getName());
    }

    @Test
    void idClassIsRejected() {
        rejectedUnsupported(IdClassEntity.class, "复合主键未支持: " + IdClassEntity.class.getName());
    }

    @Test
    void nonIdentityGeneratedValueIsRejected() {
        for (Class<?> type : new Class<?>[] {
            AutoGeneratedEntity.class,
            SequenceGeneratedEntity.class,
            TableGeneratedEntity.class,
            UuidGeneratedEntity.class
        }) {
            rejectedUnsupported(type, "只支持 @GeneratedValue(strategy=IDENTITY): " + type.getName() + ".id");
        }
    }

    @Test
    void generatedKeyOfUnsupportedTypeIsRejected() {
        rejectedUnsupported(
                StringGeneratedEntity.class, "生成键只支持 Integer / Long: " + StringGeneratedEntity.class.getName() + ".id");
    }

    @Test
    void versionOfUnsupportedTypeIsRejected() {
        rejectedUnsupported(
                ShortVersionEntity.class,
                "@Version 只支持 Integer / Long: " + ShortVersionEntity.class.getName() + ".version");
    }

    @Test
    void embeddedIsRejected() {
        rejectedUnsupported(EmbeddedEntity.class, "@Embedded 未支持: " + EmbeddedEntity.class.getName() + ".address");
    }

    @Test
    void convertIsRejected() {
        rejectedUnsupported(ConvertEntity.class, "@Convert 未支持: " + ConvertEntity.class.getName() + ".status");
    }

    @Test
    void annotationsOnGetterAreRejected() {
        rejectedUnsupported(GetterAccessEntity.class, "只支持字段访问（注解须在字段上）: " + GetterAccessEntity.class.getName());
    }

    @Test
    void entityInheritanceIsRejected() {
        rejectedUnsupported(InheritanceChildEntity.class, "实体继承未支持: " + InheritanceChildEntity.class.getName());
        rejectedUnsupported(JoinedInheritanceEntity.class, "实体继承未支持: " + JoinedInheritanceEntity.class.getName());
    }

    @Test
    void unsupportedColumnTypeIsRejected() {
        rejectedUnsupported(
                BooleanFlagEntity.class, "不支持的列类型: " + BooleanFlagEntity.class.getName() + ".flag: boolean");
        rejectedUnsupported(
                DoubleScoreEntity.class, "不支持的列类型: " + DoubleScoreEntity.class.getName() + ".score: double");
        rejectedUnsupported(ShortScoreEntity.class, "不支持的列类型: " + ShortScoreEntity.class.getName() + ".score: short");
        rejectedUnsupported(
                BigDecimalScoreEntity.class,
                "不支持的列类型: " + BigDecimalScoreEntity.class.getName() + ".score: " + BigDecimal.class.getName());
        rejectedUnsupported(
                InstantEntity.class,
                "不支持的列类型: " + InstantEntity.class.getName() + ".createdAt: " + Instant.class.getName());
        rejectedUnsupported(
                TimestampEntity.class,
                "不支持的列类型: " + TimestampEntity.class.getName() + ".createdAt: " + Timestamp.class.getName());
    }

    @Test
    void entityWithoutNoArgConstructorIsRejected() {
        rejected(NoNoArgCtorEntity.class, "实体缺少无参构造: " + NoNoArgCtorEntity.class.getName());
    }

    @Test
    void notInsertableOrUpdatableColumnIsRejected() {
        rejectedUnsupported(
                NotInsertableEntity.class,
                "@Column(insertable/updatable=false) 未支持: " + NotInsertableEntity.class.getName() + ".name");
        rejectedUnsupported(
                NotUpdatableEntity.class,
                "@Column(insertable/updatable=false) 未支持: " + NotUpdatableEntity.class.getName() + ".name");
    }

    // ===== 拒绝用例的实体夹具 =====

    static class NoEntityClass {
        @Id
        long id;
    }

    @Entity
    static class NoIdEntity {
        String name;
    }

    @Entity
    static class TwoIdEntity {
        @Id
        long id;

        @Id
        long other;
    }

    @Embeddable
    static class CompositeKey {
        long id;
        long other;
    }

    @Entity
    static class EmbeddedIdEntity {
        @EmbeddedId
        CompositeKey key;
    }

    static class SimpleKey {
        long id;
        long other;
    }

    @Entity
    @IdClass(SimpleKey.class)
    static class IdClassEntity {
        @Id
        long id;

        @Id
        long other;
    }

    @Entity
    static class AutoGeneratedEntity {
        @Id
        @GeneratedValue(strategy = GenerationType.AUTO)
        long id;
    }

    @Entity
    static class SequenceGeneratedEntity {
        @Id
        @GeneratedValue(strategy = GenerationType.SEQUENCE)
        long id;
    }

    @Entity
    static class TableGeneratedEntity {
        @Id
        @GeneratedValue(strategy = GenerationType.TABLE)
        long id;
    }

    @Entity
    static class UuidGeneratedEntity {
        @Id
        @GeneratedValue(strategy = GenerationType.UUID)
        long id;
    }

    @Entity
    static class StringGeneratedEntity {
        @Id
        @GeneratedValue(strategy = GenerationType.IDENTITY)
        String id;
    }

    @Entity
    static class ShortVersionEntity {
        @Id
        long id;

        @Version
        short version;
    }

    @Entity
    static class EmbeddedEntity {
        @Id
        long id;

        @Embedded
        Address address;
    }

    @Embeddable
    static class Address {
        String city;
    }

    @Entity
    static class ConvertEntity {
        @Id
        long id;

        @Convert(converter = StatusConverter.class)
        ItemStatus status;
    }

    @Converter
    static class StatusConverter implements AttributeConverter<ItemStatus, String> {
        @Override
        public String convertToDatabaseColumn(ItemStatus attribute) {
            return attribute == null ? null : attribute.name();
        }

        @Override
        public ItemStatus convertToEntityAttribute(String dbData) {
            return dbData == null ? null : ItemStatus.valueOf(dbData);
        }
    }

    @Entity
    static class GetterAccessEntity {
        @Id
        long id;

        String name;

        @Enumerated
        public ItemStatus getStatus() {
            return null;
        }
    }

    @Entity
    static class InheritanceBaseEntity {
        @Id
        long id;
    }

    @Entity
    static class InheritanceChildEntity extends InheritanceBaseEntity {
        String name;
    }

    @Entity
    @Inheritance(strategy = InheritanceType.JOINED)
    static class JoinedInheritanceEntity {
        @Id
        long id;
    }

    @Entity
    static class BooleanFlagEntity {
        @Id
        long id;

        boolean flag;
    }

    @Entity
    static class DoubleScoreEntity {
        @Id
        long id;

        double score;
    }

    @Entity
    static class ShortScoreEntity {
        @Id
        long id;

        short score;
    }

    @Entity
    static class BigDecimalScoreEntity {
        @Id
        long id;

        BigDecimal score;
    }

    @Entity
    static class InstantEntity {
        @Id
        long id;

        Instant createdAt;
    }

    @Entity
    static class TimestampEntity {
        @Id
        long id;

        Timestamp createdAt;
    }

    @Entity
    static class NoNoArgCtorEntity {
        @Id
        long id;

        NoNoArgCtorEntity(long id) {
            this.id = id;
        }
    }

    @Entity
    static class NotInsertableEntity {
        @Id
        long id;

        @Column(insertable = false)
        String name;
    }

    @Entity
    static class NotUpdatableEntity {
        @Id
        long id;

        @Column(updatable = false)
        String name;
    }

    enum ItemStatus {
        NEW,
        ACTIVE,
        DONE
    }
}
